"""TOI-421 b (TIC 94986319) JWST white-light fits: collect fits/*.json into a table + residual plots.
Conventions as in fit_wlc.py (P 5.19759807 d, ref T0 BTJD 1441.283952, circular, a/R* 13.76 unless variant c).
Comparison: prediction of 2026-10-28 b = 0.963 +- 0.005 (2023.7) vs the SPOC 2018-2020 epoch fold b = 0.935 +- 0.007.
Usage: python -I summarize.py <fitsdir> <out_table.md> <plotdir>
"""
import sys, json, glob, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

fd, out, pd = sys.argv[1:4]
rows = []
for fn in sorted(glob.glob(os.path.join(fd, "*_var*.json"))):
    r = json.load(open(fn))
    p, d = r["params"], r["derived"]
    beta = max(r["diag"]["beta_time_avg"].values())
    b = p["b"]
    sb = 0.5 * (b["plus"] + b["minus"])
    rows.append(dict(label=r["label"], var=r["variant"], b=b, sb=sb, beta=beta, k=p["k"], tc=d["tc_minus_pred_min"],
                     T14=d["T14_h"], T23=d["T23_h"], aR=d["aR"], u1=d["u1"]["median"], u2=d["u2"]["median"],
                     corr=r["corr_b_k"], corr_aR=r["corr_b_aR"], rc2=r["diag"]["redchi2_raw_err"],
                     jit=r["diag"]["jitter_ppm"], rms=r["diag"]["rms_ppm"], nsteps=r["nsteps"],
                     taumax=max(r["autocorr"].values()), intr=r["diag"]["inTransit_5min_bins"],
                     oot=r["diag"]["outOfTransit_5min_bins"]))


def f(s, n=4):
    return f"{s['median']:.{n}f} +{s['plus']:.{n}f}/-{s['minus']:.{n}f}"


L = ["| data | var | b | b sigma x beta | k | tc O-C (min) | T14 (h) | T23 (h) | a/R* | u1, u2 | corr(b,k) | "
     "red.chi2 (raw err) | jitter ppm | beta | z vs 0.963 | z vs 0.935 | steps / max tau |",
     "|" + "---|" * 17]
for r in rows:
    sbb = r["sb"] * r["beta"]
    z1 = (r["b"]["median"] - 0.963) / np.hypot(sbb, 0.005)
    z2 = (r["b"]["median"] - 0.935) / np.hypot(sbb, 0.007)
    ca = f" (corr b,aR {r['corr_aR']:.2f})" if r["corr_aR"] is not None else ""
    L.append(f"| {r['label']} | {r['var']} | {f(r['b'])} | {sbb:.4f} | {f(r['k'])} | {f(r['tc'], 2)} | {f(r['T14'], 3)} | "
             f"{f(r['T23'], 3)} | {f(r['aR'], 2)}{ca} | {r['u1']:.3f}, {r['u2']:.3f} | {r['corr']:.2f} | {r['rc2']:.2f} | "
             f"{r['jit']:.0f} | {r['beta']:.2f} | {z1:+.1f} | {z2:+.1f} | {r['nsteps']} / {r['taumax']:.0f} |")
L.append("")
L.append("Spot-crossing / residual check (5-min bins, MAP model): in-transit n, max|z|, mean z^2; out-of-transit same")
for r in rows:
    L.append(f"- {r['label']} var {r['var']}: in-transit n={r['intr']['n']} max|z|={r['intr']['max_abs_z']:.2f} "
             f"mean z^2={r['intr']['chi2_per_bin']:.2f} max positive resid {r['intr']['max_pos_resid_ppm']:.0f} ppm; "
             f"out-of-transit n={r['oot']['n']} max|z|={r['oot']['max_abs_z']:.2f} mean z^2={r['oot']['chi2_per_bin']:.2f}")
open(out, "w").write("# TOI-421 b (TIC 94986319) JWST white-light fit table (generated by summarize.py)\n"
                     "# conventions: P 5.19759807 d, ref T0 BTJD 1441.283952, circular, batman quadratic, "
                     "a/R* 13.76 fixed except var c; z uses sigma_b x beta, plus +-0.005 prediction error for 0.963 and +-0.007 (SPOC 2018-2020 epoch fold) for the constant 0.935\n\n"
                     + "\n".join(L) + "\n")
print("\n".join(L))

os.makedirs(pd, exist_ok=True)
for fn in sorted(glob.glob(os.path.join(fd, "*_varb_resid.npz"))):
    d = np.load(fn)
    t, fl, m, r = d["t"], d["f"], d["model"], d["resid"]
    tt = (t - t[0]) * 24
    fig, ax = plt.subplots(2, 1, figsize=(8, 6), sharex=True)
    nb = 30
    n = len(t) // nb
    tb = tt[:n * nb].reshape(n, nb).mean(1)
    ax[0].plot(tt, fl, ",", color="0.7")
    ax[0].plot(tb, fl[:n * nb].reshape(n, nb).mean(1), "o", ms=3)
    ax[0].plot(tt, m, "r-", lw=1)
    ax[1].plot(tb, r[:n * nb].reshape(n, nb).mean(1) * 1e6, "o", ms=3)
    ax[1].axhline(0, color="r")
    ax[1].set_ylabel("resid (ppm)"); ax[1].set_xlabel("hours since first integration")
    vis = "visit 2023-09-10 NIRSpec G395M NRS1" if "V1_" in fn else "visit 2023-11-06 NIRISS SOSS order 1"
    ax[0].set_title(os.path.basename(fn).replace("_resid.npz", "") + "\nTOI-421 b; " + vis + "; a/R* 13.76 fixed; LD fixed ExoTiC-LD MPS1",
                    fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(pd, os.path.basename(fn).replace(".npz", ".png")), dpi=110)
    plt.close(fig)
